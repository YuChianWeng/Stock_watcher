/** 分時時間軸刻度由 session 的 start／end 推算（契約 F-8，issue #7） */
import { describe, expect, it } from "vitest";
import { sessionTicks } from "../src/ui/chart";

const lab = (s: string, e: string) => sessionTicks(s, e).map((t) => `${t.label}@${t.minute}`);

describe("sessionTicks", () => {
  it("半天時段 09:00–12:00 → 09:00／10:00／11:00／12:00，位置與文字一致", () => {
    expect(lab("2026-11-05T09:00:00+08:00", "2026-11-05T12:00:00+08:00")).toEqual(["09:00@0", "10:00@60", "11:00@120", "12:00@180"]);
  });
  it("一般時段 09:00–13:30：13:00 離收盤 30 分鐘不標，避免重疊", () => {
    expect(lab("2026-11-05T09:00:00+08:00", "2026-11-05T13:30:00+08:00")).toEqual(["09:00@0", "10:00@60", "11:00@120", "12:00@180", "13:30@270"]);
  });
  it("非整點開盤（09:30–13:30）與 UTC 表示法", () => {
    expect(lab("2026-11-05T01:30:00Z", "2026-11-05T05:30:00Z")).toEqual(["09:30@0", "10:00@30", "11:00@90", "12:00@150", "13:30@240"]);
  });
  it("時段無效回空陣列", () => {
    expect(sessionTicks("bad", "2026-11-05T12:00:00+08:00")).toEqual([]);
    expect(sessionTicks("2026-11-05T12:00:00+08:00", "2026-11-05T09:00:00+08:00")).toEqual([]);
  });
});
